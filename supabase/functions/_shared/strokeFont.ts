/** Advance width (in cap-height units) including letter spacing. */
export const ADVANCE = 0.78;
export const SPACE_ADVANCE = 0.5;

/** Normalises free text to the characters this font can actually cut. */
export function normalizeEngravingText(input: string): string {
  return input
    .toUpperCase()
    .replace(/[\u2010-\u2015]/g, "-")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/\s+/g, " ")
    .split("")
    .filter((ch) => ch === " " || ch in G)
    .join("")
    .trim();
}

export function glyph(ch: string): Polyline[] | null {
  return G[ch] ?? null;
}

/** Total advance width of a string, in cap-height units. */
export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += ch === " " ? SPACE_ADVANCE : ADVANCE;
  return Math.max(0, w - 0.2);
}
